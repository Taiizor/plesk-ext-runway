"""Assemble helper/ sources into the standalone privileged helper, without executing them.

    python scripts/build_helper.py          # regenerate src/sbin/runway-helper
    python scripts/build_helper.py --check  # fail on invalid sources or a stale generated file

Source sections share the original helper's namespace and execution order. Only comments and
blank lines are added: there are no runtime imports, loaders or additional installed files.
"""

import argparse
import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_DIR = ROOT / "helper"
TARGET = ROOT / "src" / "sbin" / "runway-helper"
GENERATED_NOTICE = "# Generated by scripts/build_helper.py from helper/; edit the source sections instead.\n"
PART_RE = re.compile(r"^[a-z][a-z0-9_]*(?:/[a-z][a-z0-9_]*)*\.py$")


class SourceError(ValueError):
    """An invalid source manifest or Python section."""


def read_sources(source_dir=SOURCE_DIR):
    """Return ordered (relative name, LF-normalized text) pairs from the explicit manifest."""
    source_dir = Path(source_dir)
    try:
        parts = json.loads((source_dir / "manifest.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise SourceError("helper/manifest.json: %s" % exc) from exc
    if not isinstance(parts, list) or not parts:
        raise SourceError("helper/manifest.json must be a non-empty list of Python source paths")
    seen = set()
    sources = []
    for name in parts:
        if not isinstance(name, str) or not PART_RE.fullmatch(name):
            raise SourceError("invalid helper source path: %r" % (name,))
        if name in seen:
            raise SourceError("duplicate helper source: %s" % name)
        seen.add(name)
        path = source_dir / name
        try:
            path.resolve().relative_to(source_dir.resolve())
        except ValueError:
            raise SourceError("helper source leaves its source directory: %s" % name)
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as exc:
            raise SourceError("helper/%s: %s" % (name, exc)) from exc
        try:
            ast.parse(text, filename="helper/" + name, feature_version=(3, 8))
        except SyntaxError as exc:
            raise SourceError("helper/%s:%s: %s" % (name, exc.lineno, exc.msg)) from exc
        sources.append((name, text.rstrip("\n") + "\n"))
    unlisted = sorted(path.relative_to(source_dir).as_posix() for path in source_dir.rglob("*.py")
                      if path.relative_to(source_dir).as_posix() not in seen)
    if unlisted:
        raise SourceError("Python sources missing from helper/manifest.json: %s" % ", ".join(unlisted))
    return sources


def assemble_helper(source_dir=SOURCE_DIR):
    """Return deterministic UTF-8 bytes, rejecting changes to the isolated interpreter header."""
    sources = read_sources(source_dir)
    first_name, first = sources[0]
    header = "#!/usr/bin/python3 -I\n# -*- coding: utf-8 -*-\n"
    if not first.startswith(header):
        raise SourceError("helper/%s must start with the isolated Python shebang and UTF-8 header" % first_name)
    chunks = [header, GENERATED_NOTICE, "# Source: helper/%s\n" % first_name, first[len(header):]]
    for name, text in sources[1:]:
        chunks.extend(["\n# Source: helper/%s\n" % name, text])
    result = "".join(chunks)
    try:
        tree = ast.parse(result, filename="src/sbin/runway-helper", feature_version=(3, 8))
        compile(tree, "src/sbin/runway-helper", "exec")
    except SyntaxError as exc:
        raise SourceError("assembled helper:%s: %s" % (exc.lineno, exc.msg)) from exc
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if node.name in names:
                raise SourceError("duplicate top-level helper definition: %s" % node.name)
            names.add(node.name)
    return result.encode("utf-8")


def check_helper(target=TARGET, source_dir=SOURCE_DIR):
    """Return an empty list when the committed helper is the exact output of its sources."""
    try:
        expected = assemble_helper(source_dir)
    except SourceError as exc:
        return [str(exc)]
    try:
        actual = Path(target).read_bytes().replace(b"\r\n", b"\n")
    except OSError:
        actual = None
    if actual != expected:
        return ["src/sbin/runway-helper is missing or stale; run 'python scripts/build_helper.py'"]
    return []


def build_helper(target=TARGET, source_dir=SOURCE_DIR):
    """Regenerate the artifact only when its content changes. Return whether it was written."""
    content = assemble_helper(source_dir)
    target = Path(target)
    if target.is_file() and target.read_bytes() == content:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(content)
    return True


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="validate sources and fail when the generated helper is stale")
    args = parser.parse_args(argv)
    if args.check:
        errors = check_helper()
        for error in errors:
            print("ERROR: " + error, file=sys.stderr)
        if errors:
            return 1
        print("Helper sources and generated file match (Python 3.8 grammar OK)")
        return 0
    try:
        changed = build_helper()
    except SourceError as exc:
        print("ERROR: " + str(exc), file=sys.stderr)
        return 1
    print("%s src/sbin/runway-helper" % ("Generated" if changed else "Up to date:"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
